import type { WindowWithFair, FairValue } from "./types";

function makeFair(overrides: Partial<FairValue> & { fairProbBps: number }): FairValue {
  return {
    fairProbBps: overrides.fairProbBps,
    impliedProbBps: overrides.impliedProbBps ?? overrides.fairProbBps - 200,
    edgeBps: overrides.edgeBps ?? 200,
    breakEvenBps: overrides.breakEvenBps ?? 50,
    kellyWad: overrides.kellyWad ?? BigInt(Math.round(0.08 * 1e18)),
    sigmaWad: overrides.sigmaWad ?? BigInt(Math.round(0.0012 * 1e18)),
    tauWad: overrides.tauWad ?? BigInt(Math.round(0.5 * 1e18)),
    updatedAt: overrides.updatedAt ?? Math.floor(Date.now() / 1000),
    reason: overrides.reason ?? "ok",
    ok: true,
  };
}

